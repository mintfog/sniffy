//go:build darwin

package process

import (
	"os"
	"path/filepath"
)

func installedApps() ([]InstalledApp, error) {
	dirs := []string{"/Applications", "/System/Applications"}
	if home, err := os.UserHomeDir(); err == nil {
		dirs = append(dirs, filepath.Join(home, "Applications"))
	}
	return appBundles(dirs), nil
}
